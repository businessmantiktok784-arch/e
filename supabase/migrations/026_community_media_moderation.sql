-- 026_community_media_moderation.sql
-- Community attachment access control (security remediation, Issue D).
--
-- Before this migration the server stored uploaded bytes in the
-- `community-media` storage bucket and handed back a public URL without ever
-- recording a moderatable row. `resolvePublicUrl` listed the bucket and returned
-- a public URL for any object whose name started with the requested id, so a
-- `pending_review` upload was readable by anyone who knew its id, and the bucket
-- itself was expected to be public.
--
-- This migration makes the moderation ledger authoritative:
--
--   * `community_media` gains the columns the service writes on upload
--     (`mime_type`, `caption`, `contributor_hash`) and records who moderated a
--     row and why;
--   * the default moderation status becomes `pending_review`, so an insert that
--     forgets to set it is still hidden;
--   * the bucket is forced private. Public reads now issue a short-lived signed
--     URL only after the moderation row says the attachment is visible.
--
-- Deployment note: run this before enabling community uploads. Existing objects
-- that have no `community_media` row become unreadable until a row is added and
-- marked visible; this fails closed on purpose.

-- ----------------------------------------------------------------------------
-- Moderation columns
-- ----------------------------------------------------------------------------
ALTER TABLE public.community_media
  ADD COLUMN IF NOT EXISTS mime_type         text NULL,
  ADD COLUMN IF NOT EXISTS caption           text NULL,
  ADD COLUMN IF NOT EXISTS contributor_hash  text NULL,
  ADD COLUMN IF NOT EXISTS moderated_by      text NULL,
  ADD COLUMN IF NOT EXISTS moderated_at      timestamptz NULL,
  ADD COLUMN IF NOT EXISTS moderation_reason text NULL;

-- A row that does not say "visible" must never be public, and a newly inserted
-- row that omits the status must be hidden pending review.
ALTER TABLE public.community_media
  ALTER COLUMN moderation_status SET DEFAULT 'pending_review';

COMMENT ON COLUMN public.community_media.storage_path IS
  'Object path within the private community-media bucket. Bytes are served only via a short-lived signed URL issued after moderation.';
COMMENT ON COLUMN public.community_media.moderation_status IS
  'Only visible rows may be public. pending_review/hidden/removed rows are never served.';
COMMENT ON COLUMN public.community_media.contributor_hash IS
  'One-way hash of the contributor token that uploaded the attachment. No personal data.';
COMMENT ON COLUMN public.community_media.moderated_by IS
  'Admin identity recorded from the verified session when a moderation decision was applied.';

CREATE INDEX IF NOT EXISTS idx_community_media_moderation
  ON public.community_media (moderation_status);

-- ----------------------------------------------------------------------------
-- Row level security: only visible, public rows are readable with an anon key.
-- The server uses the service role, which bypasses RLS, and applies the same
-- rule before issuing a signed URL.
-- ----------------------------------------------------------------------------
ALTER TABLE public.community_media ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS community_media_public_read ON public.community_media;
CREATE POLICY community_media_public_read
  ON public.community_media
  FOR SELECT
  USING (moderation_status = 'visible' AND is_public = true);

-- ----------------------------------------------------------------------------
-- Storage bucket must be private. Signed URLs are still generated by the
-- service role; a public bucket would ignore every moderation decision.
-- ----------------------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('community-media', 'community-media', false)
ON CONFLICT (id) DO UPDATE SET public = false;
